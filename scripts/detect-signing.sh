#!/bin/sh
# Decides whether the signing team can use iCloud and push notifications, and writes
# BetterYouTube/Config/Detected.xcconfig (BY_ICLOUD = YES|NO), which Config/Signing.xcconfig
# reads to choose the entitlements. Run before every build by a pre-action of both schemes; the
# file is only rewritten when the answer changes, so it never causes a rebuild by itself.
#
# Xcode remembers, for every team it knows, whether it is a free "Personal Team"
# (isFreeProvisioningTeam). An unknown team, or none, gives NO: the build any account can sign.
#
# Adapted from SBU2's Scripts/detect-signing.sh.
set -eu

root="${SRCROOT:-$(cd "$(dirname "$0")/../BetterYouTube" && pwd)}"
out="$root/Config/Detected.xcconfig"
prefs="${BY_XCODE_PREFS:-com.apple.dt.Xcode}"

team="${DEVELOPMENT_TEAM:-}"
if [ -z "$team" ] && [ -f "$root/Config/Local.xcconfig" ]; then
    team=$(sed -n 's/^[[:space:]]*DEVELOPMENT_TEAM[[:space:]]*=[[:space:]]*\([A-Z0-9]*\).*/\1/p' \
        "$root/Config/Local.xcconfig" | tail -1)
fi

icloud=NO
if [ -n "$team" ]; then
    for key in IDEProvisioningTeamByIdentifier IDEProvisioningTeams; do
        free=$(defaults read "$prefs" "$key" 2>/dev/null | awk -v team="$team" '
            /\{/ { id = ""; free = "" }
            /isFreeProvisioningTeam/ { gsub(/[^01]/, "", $0); free = $0 }
            /teamID/ { v = $0; gsub(/.*= *"?|"?;.*/, "", v); id = v }
            /\}/ { if (id == team && free != "") { print free; exit } }
        ' || true)
        if [ -n "$free" ]; then
            [ "$free" = 0 ] && icloud=YES
            break
        fi
    done
fi

mkdir -p "$root/Config"
tmp="$out.$$"
printf '// Generated by scripts/detect-signing.sh: do not edit.\nBY_ICLOUD = %s\n' "$icloud" > "$tmp"
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then rm -f "$tmp"; else mv "$tmp" "$out"; fi
